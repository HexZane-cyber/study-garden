const assert=require('node:assert/strict');
const model=require('../docs/assets/contribution-model.js');
const valid={course_name:'Example course',course_url:'https://example.edu/course',category:'计算机系统',prerequisites:'程序设计基础',reason:'这是一份用于测试的完整课程推荐，包含充分的学习建议和课程说明，适合有编程基础的同学。',workload:'每周 6 小时',resources:''};
assert.equal(model.validate(valid).length,0);
assert(model.validate({...valid,course_url:'javascript:alert(1)'}).length>0);
assert(model.validate({...valid,reason:'太短'}).length>0);
const url=new URL(model.issueURL(valid));
assert.equal(url.origin,'https://github.com');
assert.equal(url.searchParams.get('template'),'course.yml');
assert.equal(url.searchParams.get('course_name'),valid.course_name);
assert(!url.searchParams.has('labels'));
const issue={number:12,title:'[课程投稿] Example',state:'open',user:{login:'example'},body:Object.entries(model.fields).map(([key,label])=>`### ${label}\n\n${valid[key]||'_No response_'}`).join('\n\n'),labels:[]};
assert.equal(model.parseIssue(issue).course_url,valid.course_url);
assert.equal(model.status(issue,{}).id,'pending');
assert.equal(model.status({...issue,labels:[{name:'help wanted'}]},{}).id,'more');
assert.equal(model.status({...issue,state:'closed'},{}).id,'closed');
assert.equal(model.status(issue,{'12':'courses/community/issue-12/'}).id,'accepted');
const article=model.article(issue);
assert(article.startsWith('---\nsubmission_issue: 12\n---'));
assert(article.includes('https://github.com/HexZane-cyber/study-garden/issues/12'));
assert.throws(()=>model.article({...issue,number:'../bad'}));
const malicious={...issue,body:issue.body.replace('Example course','<script>alert(1)</script>')};
assert(!model.article(malicious).includes('<script>'));
console.log('16 contribution assertions passed: validation, URL prefill, moderation status, safe article generation.');
