const {readFileSync} = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const root=path.join(__dirname,'..');
const source=readFileSync(path.join(root,'app.js'),'utf8').split("document.addEventListener('click'")[0];
const context=vm.createContext({localStorage:{getItem:()=>null},crypto:require('node:crypto').webcrypto});
vm.runInContext(source+`;globalThis.api={markdown,normalizeNote,normalizeCourse,isRepo,merge,defaultCourses,progress};`,context);
const a=context.api;
assert(!a.markdown('<script>alert(1)</script>').includes('<script>'));
assert(!a.markdown('[x](javascript:alert(1))').includes('href='));
assert(a.markdown('[x](https://example.com)').includes('rel="noopener noreferrer"'));
assert(a.markdown('# Hello\n\n```js\n<a>\n```').includes('&lt;a&gt;'));
assert(a.markdown('- one\n- two\n\ntext').includes('</ul><p>text</p>'));
assert.throws(()=>a.normalizeNote({id:'x',title:'x',body:'x',tags:[42]}));
assert.throws(()=>a.normalizeCourse({id:'x',title:'x',lessons:[],url:''}));
assert.throws(()=>a.normalizeCourse({id:'x',title:'x',lessons:['a'],url:'javascript:alert(1)'}));
assert(a.isRepo('HexZane-cyber/study-garden'));
assert(!a.isRepo('a/b/../../c'));
assert.equal(a.merge([{id:'a',v:1}],[{id:'a',v:2}])[0].v,2);
assert.equal(a.defaultCourses.length,6);
assert.equal(a.progress(a.defaultCourses[0]),0);
console.log('12 core assertions passed.');
